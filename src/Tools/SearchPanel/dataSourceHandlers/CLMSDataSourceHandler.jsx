  // Must be an arrow function class field (not a prototype method) so it is set as an own
  // property on each instance. AbstractBYOCDataSourceHandler.getBaseLayerForDatasetId is also
  // an arrow function field, meaning it is written to the instance during the parent constructor.
  // A prototype method defined here would be shadowed by that own property and never called.
  // Arrow function fields are initialized in declaration order (parent first, then subclass),
  // so this field overwrites the parent's value on the instance.
  // `super.getBaseLayerForDatasetId` cannot be used as a fallback: `super` resolves via the
  // prototype chain, and arrow function fields are own properties — not on the prototype.
  getBaseLayerForDatasetId = ({ datasetId, layerId }) => {
    // For VLCC multi-collection datasets, resolve the per-year/per-type BYOC collection via
    // layerId. For all other (single-collection) datasets, fall back to the first known collection.
    const collectionId =
      this.getCollectionIdByDatasetIdAndLayerId(datasetId, layerId) ?? this.KNOWN_COLLECTIONS[datasetId]?.[0];
    if (collectionId) {
      return new BYOCLayer({
        evalscript: true,
        collectionId: collectionId,
        locationId: this.KNOWN_COLLECTIONS_LOCATIONS[datasetId],
        subType: BYOCSubTypes.BYOC,
        shServiceRootUrl: getSHServiceRootUrl(),
      });
    }
  };

